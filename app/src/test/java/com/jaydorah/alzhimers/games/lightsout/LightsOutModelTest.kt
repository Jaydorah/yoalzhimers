package com.jaydorah.alzhimers.games.lightsout

import com.jaydorah.alzhimers.R
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import kotlin.random.Random

class LightsOutModelTest {

    @Test
    fun difficultiesExposeExpectedShape() {
        assertEquals(3, LightsOutDifficulty.Easy.gridSize)
        assertEquals(5, LightsOutDifficulty.Normal.gridSize)
        assertEquals(7, LightsOutDifficulty.Hard.gridSize)
        assertEquals(R.string.lo_diff_easy, LightsOutDifficulty.Easy.labelRes)
        assertEquals(R.string.lo_diff_normal, LightsOutDifficulty.Normal.labelRes)
        assertEquals(R.string.lo_diff_hard, LightsOutDifficulty.Hard.labelRes)
        assertTrue(LightsOutDifficulty.Easy.scrambleTaps < LightsOutDifficulty.Hard.scrambleTaps)
    }

    @Test
    fun isSolvedOnlyWhenAllOff() {
        assertFalse(isSolved(emptyList()))
        assertFalse(isSolved(listOf(true, false, false, false)))
        assertTrue(isSolved(listOf(false, false, false, false)))
    }

    @Test
    fun toggleAtFlipsSelfAndNeighbors() {
        val size = 3
        val board = List(size * size) { false }
        val next = toggleAt(board, size, 1, 1)
        // Center tap: self + up + down + left + right
        assertEquals(
            listOf(
                false, true, false,
                true, true, true,
                false, true, false,
            ),
            next,
        )
    }

    @Test
    fun toggleAtCornerOnlyTouchesExistingCells() {
        val size = 3
        val board = List(size * size) { false }
        val next = toggleAt(board, size, 0, 0)
        assertEquals(
            listOf(
                true, true, false,
                true, false, false,
                false, false, false,
            ),
            next,
        )
    }

    @Test
    fun toggleAtEdgeRespectsBounds() {
        val size = 3
        val board = List(size * size) { false }
        val next = toggleAt(board, size, 0, 1)
        assertEquals(
            listOf(
                true, true, true,
                false, true, false,
                false, false, false,
            ),
            next,
        )
    }

    @Test
    fun doubleToggleSameCellRestoresBoard() {
        val size = 5
        val board = List(size * size) { false }
        val once = toggleAt(board, size, 2, 3)
        val twice = toggleAt(once, size, 2, 3)
        assertEquals(board, twice)
    }

    @Test
    fun generateBoardHasCorrectSizeAndIsNotAlreadySolved() {
        LightsOutDifficulty.entries.forEachIndexed { i, d ->
            val settings = GameSettings(d)
            val board = generateBoard(settings, Random(i + 1))
            assertEquals(d.gridSize * d.gridSize, board.size)
            assertFalse(
                "${d.name} board should not start solved",
                isSolved(board),
            )
        }
    }

    @Test
    fun generateBoardIsSolvableByReplayingTaps() {
        // Boards are generated by applying toggles to all-off, so a solution
        // always exists. The first-row-guess solver must find it.
        LightsOutDifficulty.entries.forEachIndexed { i, d ->
            val settings = GameSettings(d)
            val board = generateBoard(settings, Random(100 + i))
            val presses = solve(board, d.gridSize)
            assertTrue("${d.name} board should be solvable", presses != null)
            val work = board.toMutableList()
            presses!!.forEachIndexed { idx, pressed ->
                if (pressed) applyPress(work, d.gridSize, idx / d.gridSize, idx % d.gridSize)
            }
            assertTrue("${d.name} presses should clear the board", isSolved(work))
        }
    }

    @Test
    fun stateDerivedProperties() {
        val settings = GameSettings(LightsOutDifficulty.Easy)
        val board = generateBoard(settings, Random(7))
        val state = LightsOutState(
            phase = LightsOutPhase.Playing,
            settings = settings,
            board = board,
            moves = 3,
            elapsedMs = 65_000L,
        )
        assertEquals(3, state.gridSize)
        assertEquals(board.count { it }, state.litCount)
        assertEquals("1:05", state.timeLabel)
        assertFalse(state.allOut)
    }

    /**
     * Classic Lights Out solver: decide the first row by trying all press
     * patterns, then each subsequent row is forced by the row above.
     */
    private fun solve(board: List<Boolean>, size: Int): List<Boolean>? {
        val firstRowCombos = 1 shl size
        for (mask in 0 until firstRowCombos) {
            val work = board.toMutableList()
            val presses = BooleanArray(size * size)
            for (c in 0 until size) {
                if ((mask shr c) and 1 == 1) {
                    presses[c] = true
                    applyPress(work, size, 0, c)
                }
            }
            for (r in 1 until size) {
                for (c in 0 until size) {
                    val above = work[(r - 1) * size + c]
                    if (above) {
                        presses[r * size + c] = true
                        applyPress(work, size, r, c)
                    }
                }
            }
            val lastRowClear = (0 until size).all { c -> !work[(size - 1) * size + c] }
            if (lastRowClear) {
                return presses.toList()
            }
        }
        return null
    }

    private fun applyPress(board: MutableList<Boolean>, size: Int, row: Int, col: Int) {
        fun flip(r: Int, c: Int) {
            if (r in 0 until size && c in 0 until size) board[r * size + c] = !board[r * size + c]
        }
        flip(row, col)
        flip(row - 1, col)
        flip(row + 1, col)
        flip(row, col - 1)
        flip(row, col + 1)
    }
}
